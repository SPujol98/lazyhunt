"""Minimal working profile from the ``/setup`` answers (onboarding-v2 T7, S7/S8).

After Confirm, :func:`cva.onboarding.answers.write_answers` has written
``preferences.toml``, ``profile.toml`` and ``onboarding_answers.json``. The bot
still stays in setup mode until the files of
:data:`cva.setup_mode.REQUIRED_PROFILE_FILES` exist; this module creates the
ones that are missing, from the answers only:

=========================  ====================================================
file                       content
=========================  ====================================================
``claims.json``            the identity claim (id = ``profile.toml [identity]
                           identity_claim_id``): ``name · city · email ·
                           linkedin`` as typed; the phone claim
                           (``<family>-phone``) when a phone was given; the
                           ``setup-*`` claims of the background answers (T8,
                           see below). Nothing else (projects are not asked:
                           :data:`GAPS`)
``synonyms.json``          ``{}`` (no claim to point an alias at yet)
``judge/facts.md``         target positions, level, work modes, work location,
                           minimum salary, spoken languages and main skills,
                           as answered
``judge/anchors.md``       only the generated marker (no reviewed offers yet)
``judge/rubric_persona.md``  per-family rules (built-in ``ai``/``backend``, a
                           generic text for the user's own titles) and per-level
                           experience rules; every slot non-empty
=========================  ====================================================

The texts come from ``templates/<lang>.toml`` and carry the "generated by
/setup" marker. A file that already exists is never touched (``skipped``),
with one exception: the ``setup-*`` claims.

``setup-*`` claims (T8, S9): every background answer becomes claims with a
stable, readable id, so a later editor can list, edit or delete them:

=======================  ==============  ======================================
id                       category        text (tags)
=======================  ==============  ======================================
``setup-lang-<code>``    ``language``    ``<Language> — <level>`` (the language
``setup-lang-<slug>``                    name); ``<code>`` for a common one,
                                         the slug of a typed name otherwise
``setup-skill-<slug>``   ``skill``       the skill as typed (the skill)
``setup-experience``     ``experience``  the years answer, then ``Last role:
                                         <role> at <company>`` with only what
                                         was typed (role, company)
``setup-education-<slug>``  ``education``  one claim per education entry, as
                                         typed (none)
=======================  ==============  ======================================

The slug is the ASCII lowercase text (``+`` -> ``plus``, ``#`` -> ``sharp``,
anything else -> ``-``); an empty slug becomes the item's position and a
repeated id gets ``-2``, ``-3``... The ``setup-`` prefix is reserved: when
``claims.json`` exists, the claims whose id starts with it are replaced by
the ones of the current answers and every other claim keeps its exact bytes
(:func:`merge_setup_claims`); the file is rewritten only when the ``setup-*``
claims change (``updated``).
The result is loaded with the strict loaders before it is reported; when that
fails, only the files this call created are removed and
:class:`~cva.profile_identity.ProfileError` propagates.
"""

